def npa_basis_size_heatmap(
    N_max: int,
    npa_level_max: int,
    *,
    show: bool = True,
    save_path: Optional[Path] = None,
) -> np.ndarray:
    """Generate a heatmap of NPA basis sizes for varying N and NPA level.

    This computes basis sizes on the fly (fast for small N/levels).

    Args:
        N_max: Maximum number of spins.
        npa_level_max: Maximum NPA level.
        show: Whether to call plt.show().
        save_path: If provided, save figure to this path.

    Returns:
        2D array of basis sizes: sizes[level_idx, N_idx].
    """
    N_values = np.arange(1, N_max + 1)
    levels = np.arange(1, npa_level_max + 1)

    sizes = np.array(
        [[len(generate_npa_basis(N=N, k=lvl).words) for N in N_values] for lvl in levels],
        dtype=int,
    )

    fig, ax = plt.subplots(figsize=(10, 6))
    im = ax.imshow(sizes, origin="lower", aspect="auto", cmap="viridis")

    cbar = plt.colorbar(im, ax=ax)
    cbar.set_label("NPA basis size")

    ax.set_xticks(np.arange(len(N_values)))
    ax.set_xticklabels(N_values)
    ax.set_yticks(np.arange(len(levels)))
    ax.set_yticklabels(levels)
    ax.set_xlabel("Number of spins N")
    ax.set_ylabel("NPA level k")
    ax.set_title("NPA Basis Size vs N and Level")

    # Annotate cells
    threshold = sizes.max() / 2
    for yi, lvl in enumerate(levels):
        for xi, N in enumerate(N_values):
            val = sizes[yi, xi]
            color = "white" if val > threshold else "black"
            ax.text(xi, yi, str(val), ha="center", va="center", color=color, fontsize=8)

    plt.tight_layout()
    if save_path is not None:
        plt.savefig(save_path)
    if show:
        plt.show()

    return sizes


def plot_basis_size_comparison(
    N_values: Iterable[int],
    *,
    npa_levels: Iterable[int] = (1, 2, 3),
    include_paper_basis: bool = True,
    logy: bool = True,
    show: bool = True,
    save_path: Optional[Path] = None,
) -> Dict[str, np.ndarray]:
    """Compare basis sizes of different NPA levels and the Heisenberg paper basis.

    This computes basis sizes on the fly.

    Args:
        N_values: System sizes to compare.
        npa_levels: NPA levels to include.
        include_paper_basis: Whether to include the Heisenberg paper basis.
        logy: Use log scale for y-axis.
        show: Whether to call plt.show().
        save_path: If provided, save figure to this path.

    Returns:
        Dict with N and basis sizes for each method.
    """
    Ns = np.array(list(N_values), dtype=int)
    npa_levels = list(npa_levels)
    result: Dict[str, np.ndarray] = {"N": Ns}

    for lvl in npa_levels:
        sizes = np.array([len(generate_npa_basis(N=N, k=lvl).words) for N in Ns])
        result[f"npa_k{lvl}"] = sizes

    if include_paper_basis:
        paper_sizes = np.array([len(generate_heisenberg_paper_basis(N=N)) for N in Ns])
        result["heisenberg_paper"] = paper_sizes

    # Plot
    fig, ax = plt.subplots(figsize=(10, 6))

    for lvl in npa_levels:
        ax.plot(Ns, result[f"npa_k{lvl}"], marker="o", linewidth=2, label=f"NPA k={lvl}")

    if include_paper_basis:
        ax.plot(Ns, result["heisenberg_paper"], marker="s", linewidth=2, linestyle="--", label="Heisenberg paper")

    if logy:
        ax.set_yscale("log")

    ax.set_xlabel("Number of spins N")
    ax.set_ylabel("Basis size")
    ax.xaxis.set_major_locator(MaxNLocator(integer=True))
    ax.set_title("Basis Size Comparison")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend()

    plt.tight_layout()
    if save_path is not None:
        plt.savefig(save_path)
    if show:
        plt.show()

    return result


